"""LaTeX support: find every citation in a .tex project, check each against the
library, and write a .bib containing exactly the cited (verified) references.
"""

from __future__ import annotations

import difflib
import re
from pathlib import Path

from .bibtex import bib_entry
from .csl import creators, family_of, is_etal_name, year_of
from .db import Library
from .importers import parse_bibtex
from .resolvers import is_agu_manuscript_number
from .textutil import fold, normalize_punct, strip_markup, title_words

# \cite, \citep, \citet*, \citealp, \parencite, \textcite, \autocite, \footcite, \citeauthor, \nocite, \Citet ...
_CITE_CMD = re.compile(
    r"\\(?P<cmd>[A-Za-z]*[Cc]ite[A-Za-z]*|nocite)\*?"
    r"(?P<opts>(?:\s*\[[^\]]*\]){0,2})\s*\{(?P<keys>[^}]*)\}")
# biblatex multicite: \cites(pre)(post)[pre][post]{a}[pre][post]{b}
_MULTI_CMD = re.compile(r"\\(?P<cmd>[A-Za-z]*[Cc]ites)\b(?P<body>(?:\s*\([^)]*\))*(?:\s*(?:\[[^\]]*\]){0,2}\s*\{[^}]*\})+)")
_INPUT = re.compile(r"\\(?:input|include|subfile|import\{[^}]*\}|subimport\{[^}]*\})\s*\{([^}]+)\}")
_BIBRES = re.compile(r"\\(?:bibliography|addbibresource(?:\[[^\]]*\])?|addglobalbib|addsectionbib)\s*\{([^}]+)\}")


def _strip_comments(text: str) -> str:
    out = []
    for line in text.splitlines():
        m = re.search(r"(?<!\\)%", line)
        out.append(line[: m.start()] if m else line)
    return "\n".join(out)


def scan_tex(path: str | Path) -> dict:
    """Collect cite keys (in order of first use), bibliography files, and the files scanned."""
    root = Path(path).expanduser().resolve()
    base = root.parent
    seen_files: list[str] = []
    keys: list[str] = []
    occurrences: dict[str, list[str]] = {}
    bib_files: list[str] = []
    nocite_all = False

    def visit(p: Path):
        nonlocal nocite_all
        if not p.exists() and p.with_suffix(".tex").exists():
            p = p.with_suffix(".tex")
        if not p.exists() or str(p) in seen_files:
            return
        seen_files.append(str(p))
        text = _strip_comments(p.read_text(encoding="utf-8", errors="replace"))
        lines = text.splitlines()
        found: list[tuple[int, str]] = []
        for m in _CITE_CMD.finditer(text):
            for k in m.group("keys").split(","):
                k = k.strip()
                if k:
                    found.append((m.start(), k))
        for m in _MULTI_CMD.finditer(text):
            for km in re.finditer(r"\{([^}]*)\}", m.group("body")):
                for k in km.group(1).split(","):
                    if k.strip():
                        found.append((m.start(), k.strip()))
        for pos, k in sorted(found):
            if k == "*":
                nocite_all = True
                continue
            line_no = text.count("\n", 0, pos) + 1
            loc = f"{p.name}:{line_no}"
            if k not in occurrences:
                keys.append(k)
                occurrences[k] = []
            occurrences[k].append(loc)
        for m in _BIBRES.finditer(text):
            for b in m.group(1).split(","):
                b = b.strip()
                if b:
                    bp = (p.parent / b)
                    if bp.suffix != ".bib":
                        bp = bp.with_suffix(".bib") if not bp.name.endswith(".bib") else bp
                    bib_files.append(str(bp))
        for m in _INPUT.finditer(text):
            child = (p.parent / m.group(1).strip())
            visit(child)
            if not child.exists():
                visit(base / m.group(1).strip())
        del lines

    visit(root)
    return {"files": seen_files, "keys": keys, "occurrences": occurrences, "bib_files": sorted(set(bib_files)),
            "nocite_all": nocite_all}


def _suggest(lib: Library, key: str) -> list[dict]:
    """Guess what a missing key meant: near-identical keys, then a search on the words inside the key."""
    out = []
    all_keys = [r[0] for r in lib.q("SELECT citekey FROM items WHERE deleted = 0 UNION SELECT alias FROM aliases")]
    for k in difflib.get_close_matches(key, all_keys, n=3, cutoff=0.8):
        it = lib.get(k, full=False)
        if it:
            out.append({"citekey": it["citekey"], "title": it["csl"].get("title"), "why": "similar key"})
    if not out:
        words = re.findall(r"[A-Z]?[a-z]+|\d{4}", key)
        q = " ".join(w for w in words if len(w) > 2)
        if q:
            items, _ = lib.search(q, limit=3)
            out += [{"citekey": i["citekey"], "title": i["csl"].get("title"), "why": "search on key words"} for i in items]
    return out


RUMIL_BIB_HEADER = "% Generated by Rumil"


def import_missing_cited(lib: Library, tex_path: str | Path, collection: str | None = None) -> dict:
    """Import, from the document's own .bib files, the cited entries that aren't in the library yet (keeping their
    keys). Returns the import report; the new entries still need verification."""
    from .importers import import_records

    scan = scan_tex(tex_path)
    missing = {k for k in scan["keys"] if lib.resolve_id(k) is None}
    records = []
    for bf in scan["bib_files"]:
        if not missing or not Path(bf).exists():
            continue
        for key, csl, extra in parse_bibtex(Path(bf).read_text(encoding="utf-8", errors="replace")):
            if key in missing:
                records.append((key, csl, extra))
                missing.discard(key)
    rep = import_records(lib, records, collection=collection, source="bib")
    rep["still_missing"] = sorted(missing)
    return rep


def check_tex(lib: Library, tex_path: str | Path, *, write_bib: str | Path | None = None, flavor: str = "bibtex",
              ascii_only: bool = False, protected=(), overwrite: bool = False) -> dict:
    scan = scan_tex(tex_path)
    report: dict = {"tex": str(Path(tex_path).expanduser()), "files_scanned": scan["files"], "cited": len(scan["keys"]),
                    "ok": [], "missing": [], "aliases": [], "problems": [], "unverified": [], "bib_files": [],
                    "fixable": [], "nocite_all": scan["nocite_all"]}
    resolved_items = []
    for k in scan["keys"]:
        it = lib.get(k, full=False)
        if not it:
            report["missing"].append({"key": k, "used_at": scan["occurrences"][k][:5], "suggestions": _suggest(lib, k)})
            continue
        if it["citekey"] != k:
            report["aliases"].append({"key": k, "library_key": it["citekey"]})
        st = it["verify_status"]
        entry = {"key": k, "title": it["csl"].get("title"), "status": st}
        if st in ("retracted", "doi_invalid", "mismatch", "differs"):
            entry["summary"] = (it.get("verify_details") or {}).get("summary")
            report["problems"].append(entry)
        elif st in ("verified", "verified_no_doi", "url_ok"):
            report["ok"].append(k)
            pending = [sg for sg in it.get("suggestions") or [] if sg.get("safe") and sg.get("kind") == "set_field"]
            if pending:  # confirmed, but would print incompletely until the safe fixes are applied
                report["fixable"].append({"key": k, "fixes": [sg.get("reason") for sg in pending]})
        else:
            report["unverified"].append(entry)
        resolved_items.append((k, it))
    # Compare with any existing .bib the document uses, entry by entry, so nothing gets worse on switching.
    report["manuscript_vs_library"] = []
    compared: set[str] = set()
    for bf in scan["bib_files"]:
        info = {"path": bf, "exists": Path(bf).exists()}
        if info["exists"]:
            try:
                entries = parse_bibtex(Path(bf).read_text(encoding="utf-8", errors="replace"))
                bib_keys = {k for k, _, _ in entries}
                info["entries"] = len(entries)
                info["cited_but_not_in_bib"] = [k for k in scan["keys"] if k not in bib_keys][:50]
                info["not_in_library"] = [k for k, _, _ in entries if k in scan["keys"] and not lib.get(k, full=False)][:50]
                for k, mcsl, _ in entries:
                    if k in scan["keys"] and k not in compared:
                        it = lib.get(k, full=False)
                        if it:
                            compared.add(k)
                            for d in compare_with_manuscript(mcsl, it["csl"]):
                                report["manuscript_vs_library"].append(dict(d, key=k, library_status=it["verify_status"]))
            except Exception as e:  # unparsable .bib
                info["error"] = str(e)
        report["bib_files"].append(info)
    if write_bib:
        out = Path(write_bib).expanduser()
        if not out.is_absolute():
            out = Path(tex_path).expanduser().parent / out
        if out.exists() and not overwrite:
            first = out.read_text(encoding="utf-8", errors="replace")[:200]
            if not first.startswith(RUMIL_BIB_HEADER):
                raise FileExistsError(f"{out} exists and was not written by Rumil; choose another file name "
                                      "(e.g. rumil-refs.bib) or pass overwrite=True")
        chunks, flagged = [], 0
        for k, it in resolved_items:
            # Write the entry under the key the document uses (aliases included), with a warning comment
            # above any entry Rumil could not confirm, so the problem is visible in the .bib itself.
            st = it["verify_status"]
            csl = it["csl"]
            warned = False
            if st not in ("verified", "verified_no_doi", "url_ok"):
                flagged += 1
                warned = True
                why = ((it.get("verify_details") or {}).get("summary") or st).replace("\n", " ")
                chunks.append(f"% RUMIL WARNING [{st}]: {why[:300]}\n")
            if is_agu_manuscript_number(str(csl.get("page") or "").split("-")[0].strip()):
                # A manuscript number (2005JE002499) is never the citation number; leave it out rather than print it.
                flagged += 0 if warned else 1
                chunks.append(f"% RUMIL WARNING [page]: '{csl['page']}' is AGU's manuscript number, not the citation "
                              "number (such as E10007), so it was left out; add the citation number in Rumil\n")
                csl = {kk: vv for kk, vv in csl.items() if kk != "page"}
            chunks.append(bib_entry(k, csl, flavor=flavor, ascii_only=ascii_only, protected=protected) + "\n")
        header = (f"{RUMIL_BIB_HEADER} from {Path(tex_path).name}: {len(resolved_items)} cited references"
                  f"{f', {flagged} not verified (see RUMIL WARNING comments)' if flagged else ''}.\n"
                  f"% Regenerate instead of editing; fix references in the Rumil library.\n\n")
        out.write_text(header + "".join(chunks), encoding="utf-8")
        report["wrote_bib"] = str(out)
        report["bib_entries_flagged"] = flagged
    report["summary"] = (f"{report['cited']} keys cited: {len(report['ok'])} verified, {len(report['unverified'])} not yet verified, "
                         f"{len(report['problems'])} with problems, {len(report['missing'])} not in library")
    if report["fixable"]:
        report["summary"] += (f"; {len(report['fixable'])} verified entries have safe fixes waiting (such as full page "
                              "ranges); apply them before writing the .bib")
    better = {d["key"] for d in report["manuscript_vs_library"] if d.get("manuscript_better")}
    if report["manuscript_vs_library"]:
        report["summary"] += (f"; {len({d['key'] for d in report['manuscript_vs_library']})} entries differ between the "
                              f"document's .bib and the library ({len(better)} where the document's .bib looks more complete)")
    return report


def _name_str(n: dict) -> str:
    return n.get("literal") or ", ".join(x for x in (n.get("family"), n.get("given")) if x)


def _initials_only(given: str) -> bool:
    """'M. S.', 'J.-P.', 'M.S.' are initials; 'Michael S.' and 'Ana' are not."""
    toks = [t for t in re.split(r"[\s\-]+", fold(given or "").strip()) if t]
    return bool(toks) and all(re.fullmatch(r"[a-z]\.?|(?:[a-z]\.){2,}", t) for t in toks)


def compare_with_manuscript(mcsl: dict, lcsl: dict) -> list[dict]:
    """Differences, in printed fields, between a document's own .bib entry and the library record for the same key.

    manuscript_better=True marks differences where the document's entry is more complete (accents, full given names,
    a subtitle, page ranges), so switching the document to a Rumil-written .bib would lose something."""
    out: list[dict] = []

    def add(field, m, l, note, better=False):
        out.append({"field": field, "manuscript": m, "library": l, "note": note, "manuscript_better": better})

    mt, lt = mcsl.get("title"), lcsl.get("title")
    if mt and lt and title_words(mt) != title_words(lt):
        longer = len(title_words(mt)) > len(title_words(lt)) and title_words(mt)[:len(title_words(lt))] == title_words(lt)
        add("title", strip_markup(mt), strip_markup(lt), "the document's title has more words" if longer
            else "title wording differs", longer)
    ma = [n for n in creators(mcsl) if not is_etal_name(n)]
    la = [n for n in creators(lcsl) if not is_etal_name(n)]
    if ma and la:
        mf = [fold(family_of(n)) for n in ma]
        lf = [fold(family_of(n)) for n in la]
        if mf != lf:
            add("author", "; ".join(_name_str(n) for n in ma[:6]), "; ".join(_name_str(n) for n in la[:6]),
                f"author lists differ ({len(ma)} vs {len(la)} names)", len(ma) > len(la) and mf[:len(lf)] == lf)
        else:
            def lost(m: str, lv: str) -> bool:
                m = normalize_punct(m)
                return bool(m and lv) and m != lv and fold(m) == fold(lv) and not m.isascii() and lv.isascii()

            accents = [(_name_str(b), _name_str(a)) for a, b in zip(ma, la)
                       if lost(a.get("family") or "", b.get("family") or "")
                       or lost(a.get("given") or "", b.get("given") or "")]
            fuller = [(_name_str(b), _name_str(a)) for a, b in zip(ma, la)
                      if _initials_only(b.get("given") or "") and a.get("given") and not _initials_only(a["given"])]
            if accents:
                add("author", "; ".join(m for _, m in accents[:4]), "; ".join(lv for lv, _ in accents[:4]),
                    "the library has lost accents the document's .bib has", True)
            if fuller:
                add("author", "; ".join(m for _, m in fuller[:4]), "; ".join(lv for lv, _ in fuller[:4]),
                    "the document's .bib has full given names where the library has initials", True)
    my, ly = year_of(mcsl), year_of(lcsl)
    if my and ly and my != ly:
        add("year", str(my), str(ly), "year differs")
    for k in ("volume", "issue", "page", "number"):
        mv = re.sub(r"\s*-+\s*", "-", normalize_punct(str(mcsl.get(k) or "")).strip()).lower()
        lv = re.sub(r"\s*-+\s*", "-", normalize_punct(str(lcsl.get(k) or "")).strip()).lower()
        if mv and lv and mv != lv:
            if k == "page" and is_agu_manuscript_number(lcsl.get(k, "").split("-")[0]):
                add(k, mcsl[k], lcsl[k], "the library has AGU's manuscript number, not the citation number", True)
            elif lv.split("-")[0] == mv.split("-")[0] and "-" in mv and "-" not in lv:
                add(k, mcsl[k], lcsl[k], "the document's .bib has the full range", True)
            else:
                add(k, mcsl[k], lcsl[k], f"{k} differs")
        elif mv and not lv:
            add(k, mcsl[k], "", f"the library has no {k}", True)
        elif lv and not mv:
            add(k, "", lcsl[k], f"the document's .bib has no {k}")
    return out
